"""Structural type shared by Coverage.py's and vfy's schema-7 data classes."""

from __future__ import annotations

from collections.abc import Callable, Collection, Mapping
from typing import Any, Protocol


class DataFile(Protocol):
    """The ``CoverageData`` methods that differential tests call on both classes."""

    def set_context(self, context: str) -> None: ...
    def add_lines(self, line_data: Mapping[str, Collection[int]]) -> None: ...
    def update(self, other_data: Any, /) -> None: ...  # noqa: ANN401 - each class accepts only its own type
    def read(self) -> None: ...
    def write(self) -> None: ...
    def lines(self, filename: str) -> list[int] | None: ...
    def contexts_by_lineno(self, filename: str) -> Mapping[int, list[str]]: ...
    def close(self, force: bool = False) -> None: ...


DataFileFactory = Callable[[str], DataFile]
