_PROFILE = "--hypothesis-profile"
_VERBOSITY = "--hypothesis-verbosity"
_STATISTICS = "--hypothesis-show-statistics"
_SEED = "--hypothesis-seed"
_EXPLAIN = "--hypothesis-explain"
_OPTIONS = (_PROFILE, _VERBOSITY, _STATISTICS, _SEED, _EXPLAIN)
_STATS = "_hypothesis_stats"
_EXAMPLES = "_hypothesis_failing_examples"


class _Store:
    def __init__(self, config: Config, reporter: Callable[[object], None]) -> None:
        self.config = config
        self.reporter = reporter
        self.messages: list[str] = []

    def __call__(self, message: object) -> None:
        if self.config.getoption("capture", "fd") == "no":
            self.reporter(message)
        self.messages.append(message if isinstance(message, str) else repr(message))


def _enabled_options(config: Config) -> bool:
    return any(config.getoption(option) for option in _OPTIONS)


def _prepare_property(item: Item) -> None:
    # Hypothesis is optional and loads only once a property test is found.
    from hypothesis import HealthCheck, settings  # noqa: PLC0415 - optional test runtime
    from hypothesis.internal.healthcheck import (  # noqa: PLC0415 - optional test runtime
        fail_health_check,
    )

    current = cast(
        "Settings", getattr(item.obj, "_hypothesis_internal_use_settings", settings.default)
    )
    checks = {HealthCheck.function_scoped_fixture, HealthCheck.differing_executors}
    parametrized_fixture = False
    if not checks.issubset(current.suppress_health_check):
        request = cast("Any", item)._request
        for name, scope, parametrized, explicit in request.fixture_info():
            parametrized_fixture |= parametrized
            if explicit and scope == "function":
                fail_health_check(
                    current,
                    f"{item.nodeid!r} uses a function-scoped fixture {name!r}."
                    "\n\nFunction-scoped fixtures are not reset between inputs "
                    "generated by `@given(...)`, which is often surprising and "
                    "can cause subtle test bugs."
                    "\n\nIf you were expecting the fixture to run separately "
                    "for each generated input, then unfortunately you "
                    "will need to find a different way to achieve your "
                    "goal (for example, replacing the fixture with a similar "
                    "context manager inside of the test)."
                    "\n\nIf you are confident that your test will work correctly "
                    "even though the fixture is not reset between generated "
                    "inputs, you can suppress this health check with "
                    "@settings(suppress_health_check=[HealthCheck.function_scoped_fixture]). "
                    "See https://hypothesis.readthedocs.io/en/latest/reference/api.html"
                    "#hypothesis.HealthCheck for details.",
                    HealthCheck.function_scoped_fixture,
                )
    if parametrized_fixture or item.get_closest_marker("parametrize") is not None:
        function = cast("Any", getattr(item.obj, "__func__", item.obj))
        function._hypothesis_internal_use_settings = settings(
            parent=current,
            suppress_health_check=set(current.suppress_health_check)
            | {HealthCheck.differing_executors},
        )
        inner = cast("Any", item.obj).hypothesis.inner_test
        inner._hypothesis_internal_add_digest = item.nodeid.encode()


def _validate_test(item: Item) -> None:
    from hypothesis.errors import InvalidArgument  # noqa: PLC0415 - optional test runtime

    if getattr(item.obj, "is_hypothesis_strategy_function", False):
        raise InvalidArgument(
            f"{item.nodeid} is a function that returns a Hypothesis strategy, "
            "but pytest has collected it as a test function.  This is useless "
            "as the function body will never be executed.  To define a test "
            "function, use @given instead of @composite."
        )
    for name, attribute in (
        ("example", "hypothesis_explicit_examples"),
        ("seed", "_hypothesis_internal_use_seed"),
        ("settings", "_hypothesis_internal_settings_applied"),
        ("reproduce_example", "_hypothesis_internal_use_reproduce_failure"),
    ):
        if hasattr(item.obj, attribute):
            raise InvalidArgument(
                f"Using `@{name}` on a test without `@given` is completely pointless."
            )


def _fixture_guard(config: Config) -> None:
    try:
        module = import_module("vfy.independent.fixtures")
    except ModuleNotFoundError as error:
        if error.name != "vfy.independent.fixtures":
            raise
        raise _pytest.UnsupportedFeatureError(
            "Hypothesis requires the native fixture-definition protocol"
        ) from error
    marker = cast("Any", module).FixtureFunctionMarker
    previous = marker.__call__

    def validate(marker_instance: object, function: object) -> object:
        if "hypothesis" in sys.modules:
            from hypothesis import is_hypothesis_test  # noqa: PLC0415 - active decorator protocol

            if is_hypothesis_test(function):
                name = cast("Any", function).__name__
                raise RuntimeError(
                    f"Can't apply @pytest.fixture() to {name} because "
                    "it is already decorated with @hypothesis.given()"
                )
        return previous(marker_instance, function)

    def restore() -> None:
        type.__setattr__(marker, "__call__", previous)

    type.__setattr__(marker, "__call__", validate)
    try:
        config.add_cleanup(restore)
    except BaseException:
        restore()
        raise


class _HypothesisPlugin:
    _history: Any

    def __init__(self, patch_message: str) -> None:
        self._patch_message = patch_message
        self.pytest_runtest_makereport = _pytest.independent_hypothesis_report(globals())

    def pytest_addoption(self, parser: Parser) -> None:
        group = parser.getgroup("hypothesis", "Hypothesis")
        group.addoption(
            _PROFILE, action="store", help="Load in a registered hypothesis.settings profile"
        )
        group.addoption(
            _VERBOSITY,
            action="store",
            choices=("quiet", "normal", "verbose", "debug"),
            help="Override profile with verbosity setting specified",
        )
        group.addoption(
            _STATISTICS,
            action="store_true",
            default=False,
            help="Configure when statistics are printed",
        )
        group.addoption(_SEED, action="store", help="Set a seed to use for all Hypothesis tests")
        group.addoption(
            _EXPLAIN,
            action="store_true",
            default=False,
            help="Enable the `explain` phase for failing Hypothesis tests",
        )

    def pytest_configure(self, config: Config) -> None:
        config.addinivalue_line("markers", "hypothesis: Tests which use hypothesis.")
        if not _enabled_options(config):
            return
        from hypothesis import (  # noqa: PLC0415 - option-driven load
            Phase,
            Verbosity,
            core,
            settings,
        )

        profile = cast("str | None", config.getoption(_PROFILE))
        if profile:
            settings.load_profile(profile)
        verbosity = cast("str | None", config.getoption(_VERBOSITY))
        if verbosity is not None and verbosity != cast("Settings", settings.default).verbosity.name:
            name = f"{settings.get_current_profile_name()}-with-{verbosity}-verbosity"
            settings.register_profile(name, verbosity=Verbosity[verbosity])
            settings.load_profile(name)
        phases = cast("Settings", settings.default).phases
        if config.getoption(_EXPLAIN) and Phase.explain not in phases:
            name = f"{settings.get_current_profile_name()}-with-explain-phase"
            settings.register_profile(name, phases=(*phases, Phase.explain))
            settings.load_profile(name)
        seed = cast("str | None", config.getoption(_SEED))
        if seed is not None:
            try:
                cast("Any", core).global_force_seed = int(seed)
            except ValueError:
                cast("Any", core).global_force_seed = seed

    def pytest_report_header(self, config: Config) -> str | None:
        if not (
            config.option.verbose >= 1 or "hypothesis" in sys.modules or _enabled_options(config)
        ):
            return None
        from hypothesis import Verbosity, settings  # noqa: PLC0415 - lazy header consumer

        current = cast("Settings", settings.default)
        if config.option.verbose < 1 and current.verbosity < Verbosity.verbose:
            return None
        changed = current.show_changed()
        suffix = f" -> {changed}" if changed else ""
        return f"hypothesis profile {settings.get_current_profile_name()!r}{suffix}"

    @hookimpl(hookwrapper=True)
    def pytest_runtest_call(self, item: Item) -> Generator[None, object, None]:
        if "hypothesis" not in sys.modules:
            yield
            return
        from hypothesis import core, is_hypothesis_test  # noqa: PLC0415 - lazy test consumer

        core_protocol = cast("Any", core)
        core_protocol.pytest_shows_exceptiongroups = True
        core_protocol.running_under_pytest = True
        if not is_hypothesis_test(item.obj):
            _validate_test(item)
            yield
            return
        _prepare_property(item)
        # Hypothesis loads only for a property test.
        from hypothesis.internal.escalation import (  # noqa: PLC0415 - optional test runtime
            current_pytest_item,
        )
        from hypothesis.reporting import (  # noqa: PLC0415 - optional test runtime
            default,
            with_reporter,
        )
        from hypothesis.statistics import (  # noqa: PLC0415 - optional test runtime
            collector,
            describe_statistics,
        )

        store = _Store(item.config, default)

        def collect_statistics(statistics: StatisticsDict) -> None:
            statistics["nodeid"] = item.nodeid
            cast("Any", item).hypothesis_statistics = describe_statistics(statistics)

        with (
            cast("Any", collector).with_value(collect_statistics),
            with_reporter(store),
            cast("Any", current_pytest_item).with_value(item),
        ):
            yield
        if store.messages:
            cast("Any", item).hypothesis_report_information = "\n".join(store.messages)

    def pytest_terminal_summary(self, terminalreporter: TerminalReporter) -> None:
        if not self._history.terminal_is_publication_owner():
            return
        print_statistics = terminalreporter.config.getoption(_STATISTICS)
        if print_statistics:
            terminalreporter.section("Hypothesis Statistics")
        examples = self._history.hypothesis_summary(terminalreporter, globals(), print_statistics)
        # Only the observability module records output files, so a run that never
        # imported it has none and the summary need not load Hypothesis.
        observability = sys.modules.get("hypothesis.internal.observability")
        wrote_to = getattr(observability, "_WROTE_TO", ())
        if wrote_to:
            terminalreporter.section("Hypothesis")
            for filename in sorted(wrote_to):
                terminalreporter.write_line(f"observations written to {filename}")
        if examples:
            from hypothesis.extra._patching import (  # noqa: PLC0415 - upstream patch implementation
                gc_patches,
                make_patch,
                save_patch,
            )

            patch = make_patch(examples)
            try:
                gc_patches()
                filename = save_patch(patch)
            except Exception:  # noqa: BLE001 - Hypothesis suppresses patch persistence failures
                return
            if not wrote_to:
                terminalreporter.section("Hypothesis")
            terminalreporter.write_line(
                f"`git apply {filename}` to add {self._patch_message} to your code."
            )

    def pytest_collection_modifyitems(self, items: list[Item]) -> None:
        if "hypothesis" not in sys.modules:
            return
        from hypothesis import is_hypothesis_test  # noqa: PLC0415 - lazy collection consumer

        found = False
        for item in items:
            if is_hypothesis_test(item.obj):
                item.add_marker("hypothesis")
                found = True
        if found:
            # Hypothesis loads its source constants only after collection finds a property test.
            from hypothesis.internal.conjecture.providers import (  # noqa: PLC0415 - optional test runtime
                _get_local_constants,
            )

            _get_local_constants()

    def pytest_sessionstart(self, session: Session) -> None:
        import _hypothesis_globals  # noqa: PLC0415 - optional plugin initialization protocol

        cast("Any", _hypothesis_globals).in_initialization -= 1
        self._history = cast("Any", session._vfy_report)

    def pytest_ignore_collect(self, collection_path: Path, config: Config) -> bool | None:
        if collection_path.name != ".hypothesis" or not collection_path.is_dir():
            return None
        patterns = cast("list[str]", config.getini("norecursedirs"))
        if any(fnmatch(collection_path.name, pattern) for pattern in patterns):
            return None
        warnings.warn(
            "Skipping collection of '.hypothesis' directory - this usually "
            "means you've explicitly set the `norecursedirs` pytest config "
            "option, replacing rather than extending the default ignores.",
            stacklevel=1,
        )
        return True


def build_plugin(config: Config, version: str) -> _HypothesisPlugin:
    """Acquire owned aliases before initializing an explicitly admitted plugin."""
    # Hypothesis 6.159.0 renamed "failing examples" in its patch message.
    minor = int(version.split(".")[1])
    patch_message = "failing examples" if minor < 159 else "failing test cases"
    restore = install_outcome_modules()
    try:
        config.add_cleanup(restore)
    except BaseException:
        restore()
        raise
    _fixture_guard(config)
    import _hypothesis_globals  # noqa: PLC0415 - reject installed pytest before initialization

    if not os.environ.get("HYPOTHESIS_EXTEND_INITIALIZATION"):
        cast("Any", _hypothesis_globals).in_initialization += 1
        if "hypothesis" in sys.modules:
            from hypothesis.configuration import (  # noqa: PLC0415 - optional initialization protocol
                notice_initialization_restarted,
            )

            notice_initialization_restarted()
    return _HypothesisPlugin(patch_message)


def pytest_addoption(parser: Parser) -> None:
    """Reject module registration that bypasses the native plugin factory."""
    raise _pytest.UnsupportedFeatureError(
        "the maintained Hypothesis adapter requires native plugin admission"
    )
