"""Owned lifecycle adapter for the admitted Hypothesis versions.

The native bootstrap calls ``build_plugin(config, version)`` after admitting every
required service. Importing this module neither loads Hypothesis nor installs
private pytest aliases. The Hypothesis engine supplies generation, shrinking,
health checks, statistics, observability, and patch construction.
"""

